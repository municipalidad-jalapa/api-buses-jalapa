-- Segunda ruta de PRUEBA y un bus por ruta.
--
-- ESTA NO ES UNA RUTA REAL DEL SERVICIO. Existe para probar la aplicacion con
-- mas de una ruta: el selector de rutas del pasajero y la regla de dominio de
-- SCRUM-166, "cada ruta tiene un solo bus", que hasta ahora no estaba en el
-- esquema. El nombre lo dice en voz alta para que nadie la tome por buena.
--
-- Recorrido: Parque Central -> 6a Avenida -> 1a Calle -> Avenida Chipilapa ->
-- 6a Calle -> 2a Avenida -> carretera a Sanarate -> Metroplaza, y regreso por la
-- Calle Transito Rojas. Ida 119 vertices, vuelta 122.
--
-- Igual que V6, lo unico real son las CALLES: el trazado sale de OpenStreetMap
-- enrutado con OSRM sobre la red vial, calculado una sola vez al escribir esta
-- migracion. La aplicacion no consume ningun servicio de rutas en ejecucion
-- (SCRUM-166, criterio 7). Los nombres de las paradas intermedias son la calle
-- mas cercana segun OpenStreetMap, no paradas oficiales.
--
-- Como V6, se aplica en todos los entornos (QA y produccion incluidos).

-- ---------------------------------------------------------------------------
-- Un bus por ruta
-- ---------------------------------------------------------------------------
ALTER TABLE vehiculos
    ADD COLUMN ruta_id BIGINT REFERENCES rutas(id);

-- Un solo bus ACTIVO por ruta. Mismo patron que uq_registro_activo_por_dispositivo:
-- la regla se garantiza en la base, no solo en el codigo.
CREATE UNIQUE INDEX uq_vehiculo_activo_por_ruta
    ON vehiculos (ruta_id) WHERE activo AND ruta_id IS NOT NULL;

-- El bus sembrado en V5 recorre la ruta de ejemplo del Centro.
UPDATE vehiculos
   SET ruta_id = (SELECT id FROM rutas WHERE nombre = 'Ruta de ejemplo - Centro de Jalapa')
 WHERE identificador = 'BUS-01';

